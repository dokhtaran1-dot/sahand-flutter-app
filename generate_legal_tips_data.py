main_category_pattern = re.compile(r'^#\s*[۰-۹0-9]+\.?\s')
for line in lines:
    line = line.rstrip()
    if main_category_pattern.match(line):
        category = line[1:].strip()
        continue
    if line.startswith('### '):
        if current:
            notes.append(current)
        title = line[4:].strip()
        match = re.match(r'نکته\s*([۰-۹0-9]+)\s*—\s*(.*)', title)
        if match:
            idx = int(match.group(1).replace('۰','0').replace('۱','1').replace('۲','2').replace('۳','3').replace('۴','4').replace('۵','5').replace('۶','6').replace('۷','7').replace('۸','8').replace('۹','9'))
            note_title = match.group(2).strip()
        else:
            idx = len(notes) + 1
            note_title = title
        current = {'id': idx, 'category': category, 'title': title, 'content': ''}
        continue
    if current is not None:
        if not line.startswith('## ') and line != '---' and not line.startswith('# '):
            if current['content']:
                current['content'] += '\n' + line
            else:
                current['content'] = line

if current:
    notes.append(current)

# Only keep categories that begin with a number and dot
categories = []
for note in notes:
    if note['category'] and main_category_pattern.match('# ' + note['category']):
        if note['category'] not in categories:
            categories.append(note['category'])

for note in notes:
    note['content'] = note['content'].strip()

